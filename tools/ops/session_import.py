#!/usr/bin/env python3
"""Import and scope-filter a browser cookie export into a replayable session.

Usage:
  session_import.py --domain example.com --input cookies.json --out session/

Supported input shapes:
  - list of cookie objects
  - {"cookies": [...]} (Chrome extension exports)
  - {"domain": ..., "cookies": [...]}

Writes session.json, cookies.txt (Netscape) and SUMMARY.md. Never prints values.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path
from urllib.parse import urlparse

KEYS = ("name", "value", "domain", "path", "expires", "expirationDate", "secure", "httpOnly", "sameSite")


def domain_of(value: str) -> str:
    value = value.strip()
    if "://" in value:
        return (urlparse(value).hostname or "").lower().rstrip(".")
    return value.lower().lstrip(".").rstrip(".")


def load_cookies(path: Path) -> list[dict]:
    raw = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(raw, list):
        items = raw
    elif isinstance(raw, dict):
        items = raw.get("cookies") or raw.get("items") or []
    else:
        items = []
    return [item for item in items if isinstance(item, dict)]


def normalize(item: dict, fallback_domain: str) -> dict | None:
    name = str(item.get("name") or item.get("Name") or "").strip()
    value = str(item.get("value") or item.get("Value") or "")
    if not name:
        return None
    expires = item.get("expires", item.get("expirationDate", 0))
    try:
        expires = int(float(expires))
    except (TypeError, ValueError):
        expires = 0
    return {
        "name": name,
        "value": value,
        "domain": str(item.get("domain") or fallback_domain).lower().lstrip("."),
        "include_sub": str(item.get("domain") or "").startswith("."),
        "path": str(item.get("path") or "/"),
        "expires": expires,
        "secure": bool(item.get("secure", False)),
        "httpOnly": bool(item.get("httpOnly", False)),
        "sameSite": str(item.get("sameSite") or ""),
    }


def keep(cookie: dict, target: str) -> bool:
    domain = cookie["domain"].lstrip(".").lower()
    return domain == target or domain.endswith("." + target) or target.endswith("." + domain)


def to_netscape(cookies: list[dict]) -> str:
    lines = ["# Netscape HTTP Cookie File", "# Generated by session_import.py", ""]
    for c in cookies:
        domain = c["domain"]
        include_sub = "TRUE" if c.get("include_sub") else "FALSE"
        expires = c["expires"] or 0
        lines.append("\t".join([domain, include_sub, c["path"], "TRUE" if c["secure"] else "FALSE",
                                str(expires), c["name"], c["value"]]))
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description="Scope-filter browser cookies into a replay session")
    ap.add_argument("--domain", required=True, help="authorized target domain")
    ap.add_argument("--input", required=True, help="cookie JSON export")
    ap.add_argument("--out", required=True, help="output directory")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()

    target = domain_of(args.domain)
    if not target or "." not in target:
        print("session_import: --domain must be a hostname", file=sys.stderr)
        return 2
    src = Path(args.input).expanduser()
    if not src.is_file():
        print(f"session_import: input not found: {src}", file=sys.stderr)
        return 2
    try:
        items = load_cookies(src)
    except (OSError, json.JSONDecodeError) as exc:
        print(f"session_import: cannot parse JSON: {exc}", file=sys.stderr)
        return 1

    cookies = []
    for item in items:
        c = normalize(item, target)
        if c:
            cookies.append(c)
    scoped = [c for c in cookies if keep(c, target)]
    out = Path(args.out).expanduser()
    out.mkdir(parents=True, exist_ok=True)
    (out / "session.json").write_text(json.dumps({"domain": target, "cookies": scoped}, ensure_ascii=False, indent=2), encoding="utf-8")
    (out / "cookies.txt").write_text(to_netscape(scoped), encoding="utf-8")
    now = time.strftime("%Y-%m-%d %H:%M:%S")
    summary = (
        f"# Session import: {target}\n\n"
        f"- source: `{src}`\n- imported: {len(cookies)}\n- scoped: {len(scoped)}\n"
        f"- rejected: {len(cookies) - len(scoped)}\n- generated: {now}\n\n"
        "Cookie values are intentionally not printed. Use cookies.txt or session.json.\n"
    )
    (out / "SUMMARY.md").write_text(summary, encoding="utf-8")
    result = {
        "domain": target,
        "source": str(src),
        "out": str(out),
        "imported": len(cookies),
        "scoped": len(scoped),
        "rejected": len(cookies) - len(scoped),
        "names": [c["name"] for c in scoped],
    }
    if args.json:
        print(json.dumps(result, ensure_ascii=False, indent=2))
    else:
        print(f"domain={target} imported={len(cookies)} scoped={len(scoped)} rejected={len(cookies) - len(scoped)}")
        print(f"out={out}")
        print("names=" + ",".join(result["names"][:30]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
