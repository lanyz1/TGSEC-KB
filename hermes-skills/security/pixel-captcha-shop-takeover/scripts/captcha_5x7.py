def extract(path, idx):
    a = np.array(Image.open(path).convert("RGB")).astype(int)
    x0,y0,x1,y1 = BOXES[idx]
    mask = (np.abs(a[y0:y1, x0:x1] - np.array(COLORS[idx])).sum(axis=2) < 30).astype(int)
    rows = []
    for by in range(0, mask.shape[0], 4):
        rows.append(["1" if mask[by:by+4,bx:bx+4].sum() >= 6 else "0" for bx in range(0, mask.shape[1], 4)])
    return "".join("".join(r) for r in rows)

def decode(path):
    out=[]
    for i in range(4):
        cur = extract(path,i)
        best,bd=None,999
        for ch,pat in FONT.items():
            p=pat.replace(" ","")
            d=sum(1 for x,y in zip(cur,p) if x!=y)
            if d<bd: bd,best=d,ch
        out.append((best,bd))
    return out

